def glyph_mask(font, ch):
    rows = font[ch]
    return np.array([[c == "#" for c in r] for r in rows], dtype=bool)


def text_mask(text, shape, x, y, font=FONT3x5, spacing=1):
    """Boolean mask of `text` drawn at (x, y) on an array of `shape`."""
    m = np.zeros(shape, dtype=bool)
    for ch in text:
        g = glyph_mask(font, ch)
        h, w = g.shape
        m[y:y + h, x:x + w] |= g
        x += w + spacing
    return m


def text_width(text, font=FONT3x5, spacing=1):
    return sum(len(font[c][0]) + spacing for c in text) - spacing
